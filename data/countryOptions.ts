const buildCountryOptions = (): CountryOption[] => {
  if (typeof Intl.DisplayNames === "undefined") {
    return FALLBACK_COUNTRY_OPTIONS;
  }

  const displayNames = new Intl.DisplayNames(["en"], { type: "region" });
  return ISO_COUNTRY_CODES
    .map((code) => ({ code, name: displayNames.of(code) ?? code }))
    .sort((left, right) => left.name.localeCompare(right.name));
};

export const COUNTRY_OPTIONS = buildCountryOptions();
const COUNTRY_CODES = new Set(COUNTRY_OPTIONS.map((country) => country.code));

export const isSupportedCountryCode = (value: string): boolean =>
  COUNTRY_CODES.has(value.trim().toUpperCase());

export const normalizeCountryCode = (value: string, fallback = "GB"): string => {
  const normalizedValue = value.trim().toUpperCase();
  const normalizedFallback = fallback.trim().toUpperCase();

  if (isSupportedCountryCode(normalizedValue)) {
    return normalizedValue;
  }

  return isSupportedCountryCode(normalizedFallback)
    ? normalizedFallback
    : COUNTRY_OPTIONS[0]?.code ?? "GB";
};
